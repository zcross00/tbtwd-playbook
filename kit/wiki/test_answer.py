"""Tests for answer.py: python3 -m unittest discover -s kit/wiki (kit/test.sh)"""
import unittest

import answer
import gen


def event(body="1", login="zcross00", state="open", labels=("decision",), app=None):
    return {"issue": {"state": state, "labels": [{"name": l} for l in labels], "body": "**Question:** x?"},
            "comment": {"body": body, "user": {"login": login}, "performed_via_github_app": app, "created_at": "2026-10-30T21:36:32Z",
                        "html_url": "https://github.com/c/1"}}


class Answer(unittest.TestCase):
    def test_his_comment_is_quoted_dated_and_kept_above_the_question(self):
        body = answer.answer(event("B, but\n\nlater"))
        self.assertTrue(body.startswith("Decided: 2026-10-30\n\n> B, but\n>\n> later\n\nZac, 2026-10-30 21:36 UTC"))
        self.assertTrue(body.endswith("**Question:** x?"))
        # The wiki shows the first quoted line as his words.
        self.assertEqual(gen.quote(body), "B, but")

    def test_a_question_back_or_anyone_else_changes_nothing(self):
        self.assertIsNone(answer.answer(event("why not 2?")))
        self.assertIsNone(answer.answer(event(login="someone")))
        self.assertIsNone(answer.answer(event(state="closed")))
        self.assertIsNone(answer.answer(event(labels=("parked",))))

    def test_a_claude_session_posting_as_him_is_not_his_answer(self):
        self.assertIsNone(answer.answer(event(app={"slug": "claude"})))
        self.assertIsNone(answer.answer(event("Recommend A.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_")))

    def test_putting_it_off_changes_nothing(self):
        self.assertIsNone(answer.answer(event("Let me think about it")))
        self.assertIsNone(answer.answer(event("not yet, after the playtest")))


if __name__ == "__main__":
    unittest.main()
