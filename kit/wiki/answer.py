#!/usr/bin/env python3
"""Records the owner's answer to a decision from their comment on its issue,
so answering is one comment where the question is. Run by the
kit-decision-answer workflow on a new comment.

On an open issue labeled `decision`, a comment by the owner themselves (project.owner_login) (not a
Claude session posting as him) is his answer:
it goes at the top of the body as a `> ` quote (what the wiki's Decisions page
shows), with a `Decided:` date and a link to the comment, and the issue closes
as completed. A comment ending in "?" is a question back, and one starting
"not yet", "later", "let me think", "hold on" or "wait" puts it off: neither
changes anything.

    GITHUB_EVENT_PATH=event.json GH_TOKEN=... python3 kit/wiki/answer.py
"""
import json
import os
import sys
import urllib.request

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
import playbook_config  # noqa: E402

CFG = playbook_config.load()
OWNER = CFG["project"]["owner_login"]
OWNER_NAME = CFG["project"]["owner_name"]
# A Claude session's comment is posted as the owner too, through the Claude
# app (performed_via_github_app), and ends with this footer.
CLAUDE_FOOTER = "_Generated by [Claude Code]"
# Comments that put the answer off rather than give it.
NOT_YET = ("not yet", "later", "let me think", "hold on", "wait")


def answer(event):
    """The issue's new body for an answering comment, or None."""
    issue, comment = event["issue"], event["comment"]
    text = (comment["body"] or "").strip()
    if (issue["state"] != "open" or "pull_request" in issue
            or "decision" not in {l["name"] for l in issue["labels"]}
            or not OWNER or comment["user"]["login"] != OWNER or comment.get("performed_via_github_app")
            or CLAUDE_FOOTER in text or not text or text.endswith("?")
            or text.lower().startswith(NOT_YET)):
        return None
    quoted = "\n".join("> " + line if line.strip() else ">" for line in text.splitlines())
    when = comment["created_at"].replace("T", " ")[:16]
    return (f"Decided: {comment['created_at'][:10]}\n\n{quoted}\n\n"
            f"{OWNER_NAME}, {when} UTC, [on this issue]({comment['html_url']}).\n\n{issue['body'] or ''}")


def main():
    with open(os.environ["GITHUB_EVENT_PATH"], encoding="utf-8") as f:
        event = json.load(f)
    body = answer(event)
    if body is None:
        print("Not an answer; nothing to do")
        return 0
    req = urllib.request.Request(
        event["issue"]["url"], method="PATCH",
        data=json.dumps({"body": body, "state": "closed", "state_reason": "completed"}).encode(),
        headers={"Authorization": f"bearer {os.environ['GH_TOKEN']}",
                 "Accept": "application/vnd.github+json", "User-Agent": "playbook-wiki"})
    with urllib.request.urlopen(req) as r:
        print(f"Recorded the answer on #{event['issue']['number']}: {r.status}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
