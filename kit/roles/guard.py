#!/usr/bin/env python3
"""Holds agents to their thread's role (playbook/12-identities.md). Run by the
kit-role-guard workflow on issues and pull request reviews.

Agents post through the AI tool's GitHub app and stamp every post with a
`Role: overseer|architect|inquisitor` line. The owner's own actions (no app,
no AI footer) and workflow bots are never touched. For agent actions:

- An approving review needs the inquisitor stamp, or it is dismissed.
- Closing an issue needs an inquisitor comment on it first (the verification
  note), or the issue is reopened.
- A new issue needs the overseer or inquisitor stamp, or it is labelled
  `role-violation` for the retro.
- Every PR head gets a `role-guard` commit status: success once an
  inquisitor (or the owner by hand) approved that commit. The ruleset on
  `main` requires it, so it shows in the merge box.

Every correction also labels the item `role-violation` and says why.

    GITHUB_EVENT_NAME=issues GITHUB_EVENT_PATH=event.json GH_TOKEN=... python3 kit/roles/guard.py
"""
import json
import os
import re
import sys
import urllib.request

STAMP = re.compile(r"^\s*Role:\s*(overseer|architect|inquisitor)\b", re.I | re.M)
AI_FOOTER = "_Generated by [Claude Code]"
LABEL = "role-violation"


def role(body):
    """The role stamped on a post, or None."""
    m = STAMP.search(body or "")
    return m.group(1).lower() if m else None


def is_agent(body, via_app):
    """An agent's post: made through an app, or carrying the AI footer."""
    return bool(via_app) or AI_FOOTER in (body or "")


def review_action(event):
    """('dismiss', reason) for an agent approval without the inquisitor stamp."""
    review = event["review"]
    if event.get("action") != "submitted" or (review.get("state") or "").lower() != "approved":
        return None
    body = review.get("body") or ""
    if not is_agent(body, review.get("performed_via_github_app")) or role(body) == "inquisitor":
        return None
    return ("dismiss", f"Only an inquisitor approves. This approval is stamped `{role(body) or 'no role'}`.")


def pr_state(reviews, head_sha):
    """The `role-guard` status for a PR head: success once an inquisitor (or the
    owner by hand) approved that commit, else pending."""
    for r in reviews:
        if (r.get("state") or "").upper() != "APPROVED" or r.get("commit_id") != head_sha:
            continue
        body = r.get("body") or ""
        if role(body) == "inquisitor" or not is_agent(body, r.get("performed_via_github_app")):
            return "success", "Approved by an inquisitor"
    return "pending", "Waiting for an inquisitor's approval on this commit"


def close_action(event, comments, close_via_app):
    """('reopen', reason) for an agent close with no inquisitor note before it."""
    if event.get("action") != "closed" or "pull_request" in event["issue"]:
        return None
    sender = event.get("sender", {})
    if sender.get("type") == "Bot" or not close_via_app:
        return None
    closed_at = event["issue"].get("closed_at") or ""
    for c in comments:
        if c.get("created_at", "") <= closed_at and role(c.get("body")) == "inquisitor":
            return None
    return ("reopen", "Only an inquisitor closes an issue, after a verification note stamped `Role: inquisitor`.")


def open_action(event):
    """('label', reason) for an agent-opened issue without an overseer or inquisitor stamp."""
    issue = event["issue"]
    if event.get("action") != "opened" or "pull_request" in issue:
        return None
    body = issue.get("body") or ""
    if not is_agent(body, issue.get("performed_via_github_app")) or role(body) in ("overseer", "inquisitor"):
        return None
    return ("label", f"Only an overseer (or an inquisitor filing a correction) creates work items. "
                     f"This one is stamped `{role(body) or 'no role'}`.")


def api(method, url, data=None):
    req = urllib.request.Request(
        url, method=method, data=json.dumps(data).encode() if data is not None else None,
        headers={"Authorization": f"bearer {os.environ['GH_TOKEN']}",
                 "Accept": "application/vnd.github+json", "User-Agent": "playbook-role-guard"})
    with urllib.request.urlopen(req) as r:
        body = r.read()
        return json.loads(body) if body else None


def flag(issue_url, reason):
    api("POST", issue_url + "/labels", {"labels": [LABEL]})
    api("POST", issue_url + "/comments", {"body": f"Role guard: {reason} Flagged `{LABEL}` for the retro."})


def main():
    name = os.environ["GITHUB_EVENT_NAME"]
    with open(os.environ["GITHUB_EVENT_PATH"], encoding="utf-8") as f:
        event = json.load(f)
    act = None
    if name == "pull_request_review":
        act = review_action(event)
        if act:
            pr = event["pull_request"]
            api("PUT", f"{pr['url']}/reviews/{event['review']['id']}/dismissals",
                {"message": "Role guard: " + act[1]})
            flag(pr["issue_url"], act[1])
    if name in ("pull_request", "pull_request_review"):
        pr = event["pull_request"]
        head = pr["head"]["sha"]
        reviews = api("GET", pr["url"] + "/reviews?per_page=100") or []
        state, why = pr_state(reviews, head)
        api("POST", f"{pr['base']['repo']['url']}/statuses/{head}",
            {"state": state, "context": "role-guard", "description": why})
    elif name == "issues":
        issue = event["issue"]
        act = open_action(event)
        if event.get("action") == "closed":
            events = api("GET", issue["url"] + "/events?per_page=100") or []
            closes = [e for e in events if e.get("event") == "closed"]
            via_app = bool(closes and (closes[-1].get("performed_via_github_app") or closes[-1].get("commit_id")))
            comments = api("GET", issue["url"] + "/comments?per_page=100") or []
            act = close_action(event, comments, via_app)
            if act:
                api("PATCH", issue["url"], {"state": "open"})
        if act:
            flag(issue["url"], act[1])
    print(f"{name}: {act[0] if act else 'ok'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
