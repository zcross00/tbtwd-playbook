import unittest

import guard

APP = {"slug": "claude"}
FOOT = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def review(body, state="approved", app=None):
    return {"action": "submitted", "review": {"state": state, "body": body, "performed_via_github_app": app}}


class Review(unittest.TestCase):
    def test_inquisitor_approval_stands(self):
        self.assertIsNone(guard.review_action(review("Role: inquisitor\nLooks right." + FOOT)))

    def test_architect_approval_is_dismissed(self):
        self.assertEqual(guard.review_action(review("Role: architect\nLGTM" + FOOT))[0], "dismiss")

    def test_unstamped_agent_approval_is_dismissed(self):
        self.assertEqual(guard.review_action(review("ok", app=APP))[0], "dismiss")

    def test_owner_by_hand_is_left_alone(self):
        self.assertIsNone(guard.review_action(review("ship it")))

    def test_comment_review_is_ignored(self):
        self.assertIsNone(guard.review_action(review("Role: architect" + FOOT, state="commented")))


def closed(sender_type="User"):
    return {"action": "closed", "sender": {"type": sender_type},
            "issue": {"closed_at": "2026-11-07T12:00:00Z"}}


class Close(unittest.TestCase):
    NOTE = {"created_at": "2026-11-07T11:59:00Z", "body": "Role: inquisitor\nVerified on main." + FOOT}

    def test_close_after_inquisitor_note_stands(self):
        self.assertIsNone(guard.close_action(closed(), [self.NOTE], True))

    def test_close_without_note_reopens(self):
        self.assertEqual(guard.close_action(closed(), [], True)[0], "reopen")

    def test_note_after_close_does_not_count(self):
        late = dict(self.NOTE, created_at="2026-11-07T12:01:00Z")
        self.assertEqual(guard.close_action(closed(), [late], True)[0], "reopen")

    def test_owner_close_by_hand_is_left_alone(self):
        self.assertIsNone(guard.close_action(closed(), [], False))

    def test_bot_close_is_left_alone(self):
        self.assertIsNone(guard.close_action(closed("Bot"), [], True))


def opened(body, app=None):
    return {"action": "opened", "issue": {"body": body, "performed_via_github_app": app}}


class Open(unittest.TestCase):
    def test_overseer_issue_stands(self):
        self.assertIsNone(guard.open_action(opened("Role: overseer\nNew work." + FOOT)))

    def test_inquisitor_correction_stands(self):
        self.assertIsNone(guard.open_action(opened("Role: inquisitor\nCorrection." + FOOT)))

    def test_architect_issue_is_labelled(self):
        self.assertEqual(guard.open_action(opened("Role: architect\nFound a bug." + FOOT))[0], "label")

    def test_owner_issue_is_left_alone(self):
        self.assertIsNone(guard.open_action(opened("an idea")))


if __name__ == "__main__":
    unittest.main()
